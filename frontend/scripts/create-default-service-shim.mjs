#!/usr/bin/env node
/**
 * Recreates src/api-client/services/DefaultService.ts after each generate:client run.
 *
 * The openapi-typescript-codegen tool splits services by tag (ApiariesService,
 * AuthService, …). This script creates a backward-compat DefaultService shim
 * that re-exports all static methods from those services.
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const servicesDir = join(__dirname, '../src/api-client/services');

// Discover all generated service files (exclude the shim itself)
const serviceFiles = readdirSync(servicesDir)
  .filter(f => f.endsWith('Service.ts') && f !== 'DefaultService.ts')
  .sort();

// Extract method names: lines matching "public static someMethod("
const serviceEntries = serviceFiles.map(file => {
  const content = readFileSync(join(servicesDir, file), 'utf8');
  const className = file.replace('.ts', '');
  const methods = [...content.matchAll(/public static (\w+)\(/g)].map(m => m[1]);
  return { className, methods };
});

// Build imports
const imports = serviceEntries
  .map(({ className }) => `import { ${className} } from './${className}';`)
  .join('\n');

// Build method assignments grouped by service
const sections = serviceEntries.map(({ className, methods }) => {
  const tag = className.replace('Service', '');
  const lines = methods.map(m => `  ${m}: ${className}.${m},`).join('\n');
  return `  // ── ${tag} ${'─'.repeat(Math.max(0, 60 - tag.length))}\n${lines}`;
}).join('\n\n');

const shim = `/* istanbul ignore file */
/* tslint:disable */
/* eslint-disable */
/**
 * BACKWARD-COMPAT SHIM — auto-generated by scripts/create-default-service-shim.mjs
 * Combines all tag-based services into a single DefaultService namespace.
 * Do not edit manually — re-run \`npm run generate:client\` to regenerate.
 */

${imports}

export const DefaultService = {
${sections}
};
`;

const outFile = join(servicesDir, 'DefaultService.ts');
writeFileSync(outFile, shim, 'utf8');
console.log(`✓ DefaultService shim written to ${outFile}`);
