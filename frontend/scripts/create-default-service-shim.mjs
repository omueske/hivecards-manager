#!/usr/bin/env node
/**
 * Recreates src/api-client/services/DefaultService.ts after each generate:client run.
 *
 * The openapi-typescript-codegen tool splits services by tag (ApiariesService,
 * AuthService, …). This script creates a backward-compat DefaultService shim
 * that re-exports all static methods from those services.
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const servicesDir = join(__dirname, '../src/api-client/services');

// Discover all generated service files (exclude the shim itself)
const serviceFiles = readdirSync(servicesDir)
  .filter((f) => f.endsWith('Service.ts') && f !== 'DefaultService.ts')
  .sort();

// Extract method names: lines matching "public static someMethod("
const serviceEntries = serviceFiles.map((file) => {
  const content = readFileSync(join(servicesDir, file), 'utf8');
  const className = file.replace('.ts', '');
  const methods = [...content.matchAll(/public static (\w+)\(/g)].map((m) => m[1]);
  return { className, methods };
});

// Build lazy-method shim: each method will dynamically import its owning
// service module when invoked to avoid import-time side-effects.
const methodLines = serviceEntries
  .map(({ className, methods }) => {
    const tag = className.replace('Service', '');
    const lines = methods
      .map((m) => `  ${m}: makeLazyMethod('./${className}', '${className}', '${m}'),`)
      .join('\n')
    return `  // ── ${tag} ${'-'.repeat(Math.max(0, 60 - tag.length))}\n${lines}`
  })
  .join('\n\n')

const shim = `/* istanbul ignore file */
/* tslint:disable */
/* eslint-disable */
/**
 * BACKWARD-COMPAT SHIM — auto-generated by scripts/create-default-service-shim.mjs
 * Lazily calls underlying service implementations to avoid import-time
 * side-effects. This makes the module safe to import in test runners and
 * environments where generated service modules may perform runtime work.
 *
 * Do not edit manually — re-run \`npm run generate:client\` to regenerate.
 */

type MethodFn = (...args: any[]) => Promise<any>

function makeLazyMethod(modulePath: string, exportName: string, methodName: string): MethodFn {
  return async (...args: any[]) => {
    const mod = await import(modulePath)
    const svc = mod[exportName] ?? mod.default ?? mod
    const fn = svc?.[methodName]
    if (typeof fn !== 'function') {
      throw new Error(methodName + ' is not available on ' + modulePath)
    }
    return fn.apply(svc, args)
  }
}

const DefaultService: Record<string, MethodFn> = {
${methodLines}
}

// Backwards-compat: some consumers import the module and expect a
// \`DefaultService\` property on it (old shim). Provide it.
(DefaultService as any).DefaultService = DefaultService

export { DefaultService }
export default DefaultService
`

const outFile = join(servicesDir, 'DefaultService.ts')
writeFileSync(outFile, shim, 'utf8')
console.log(`✓ DefaultService lazy-shim written to ${outFile}`)
